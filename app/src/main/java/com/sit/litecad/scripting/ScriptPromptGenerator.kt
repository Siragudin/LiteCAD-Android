/**
 * Генерация Markdown-промпта для браузерных ИИ (ChatGPT/DeepSeek/…) и сохранение его в «Загрузки».
 *
 * Модуль изолирован от UI. [generateMarkdown] — чистая функция (легко тестируется),
 * а [saveMarkdownToDownloads] выполняет Android-специфичную запись через MediaStore
 * (тот же механизм, что и в DxfExporter/PdfExporter).
 */
