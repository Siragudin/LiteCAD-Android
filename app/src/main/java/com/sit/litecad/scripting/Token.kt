package com.sit.litecad.scripting

/**
 * Типы лексем лёгкого скриптового движка LiteScript
 * (синтаксис максимально близок к Kotlin).
 *
 * Перечисление покрывает всё, что необходимо разобрать [Lexer] и [Parser]:
 * литералы, идентификаторы, ключевые слова, операторы, разделители и признак конца ввода.
 *
 * Однострочные комментарии `//` отбрасываются лексером и лексем не порождают;
 * многострочные `/* ... */` не поддерживаются. Массивы/коллекции (`[ ]`) также не поддерживаются.
 *
 * Имена функций рисования (`line`, `rect`, `circle`, `arc`, `gear`, `style`, `text`, `fill`)
 * и математические сущности (`PI`, `sin`, `cos`, `toRadians`) — это НЕ ключевые слова,
 * а зарезервированные идентификаторы: они лексируются как [IDENTIFIER] и распознаются
 * интерпретатором во время выполнения.
 */
enum class TokenType {
    // --- Литералы ---
    NUMBER,        // 42, 3.14
    STRING,        // "Готово"

    // --- Идентификаторы ---
    IDENTIFIER,    // line, rect, circle, arc, gear, style, text, fill, PI, sin, cos, toRadians, i, z

    // --- Ключевые слова ---
    VAL,           // val
    VAR,           // var
    FOR,           // for
    IF,            // if
    ELSE,          // else
    IN,            // in
    UNTIL,         // until
    TRUE,          // true
    FALSE,         // false

    // --- Арифметика ---
    PLUS,          // +
    MINUS,         // -
    STAR,          // *
    SLASH,         // /

    // --- Присваивание и диапазоны ---
    ASSIGN,        // =
    RANGE,         // ..

    // --- Сравнения ---
    EQEQ,          // ==
    NEQ,           // !=
    LT,            // <
    LTE,           // <=
    GT,            // >
    GTE,           // >=

    // --- Логика ---
    AND,           // &&
    OR,            // ||
    NOT,           // !

    // --- Доступ к членам ---
    DOT,           // .  (например, Math.toRadians)

    // --- Скобки и разделители ---
    LPAREN,        // (
    RPAREN,        // )
    LBRACE,        // {
    RBRACE,        // }
    COMMA,         // ,
    SEMICOLON,     // ;

    // --- Служебные ---
    EOF            // конец ввода
}

/**
 * Одна лексема, полученная [Lexer] из исходного текста скрипта.
 *
 * @property type тип лексемы (см. [TokenType]).
 * @property lexeme исходный текст лексемы без изменений (например, `"3.14"`, `"until"`, `"=="`).
 * @property line номер строки, в которой начинается лексема (1-based) — для сообщений об ошибках.
 */
data class Token(
    val type: TokenType,
    val lexeme: String,
    val line: Int
)
