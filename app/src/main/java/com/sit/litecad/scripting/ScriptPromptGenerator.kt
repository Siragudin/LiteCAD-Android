    /** Собирает Markdown-инструкцию по синтаксису LiteScript с подстановкой пользовательского запроса. */
    fun generateMarkdown(userPrompt: String): String {
        val request = userPrompt.trim().ifEmpty { EMPTY_REQUEST_PLACEHOLDER }
        return """
            |# LiteScript — сгенерируй скрипт для LiteCAD
            |
            |Ты пишешь скрипт на LiteScript для LiteCAD (2D CAD).
            |Верни только код — без пояснений и без markdown-обёрток.
            |
            |LiteScript — небольшой императивный язык, похожий на Kotlin. Скрипт состоит из
            |последовательности инструкций: объявление/присваивание переменной, управление
            |потоком (`if`/`for`) и вызовы функций рисования. Всё, что нарисовано, измеряется
            |в миллиметрах в мировых координатах.
            |
            |## Правила вывода
            |
            |- Верни ровно один скрипт, обычным текстом.
            |- Не добавляй markdown-обёртки и пояснения.
            |- Комментарии `//` внутри кода допустимы.
            |- Никаких переносов-фантазий: только инструкции и функции из этого документа.
            |- `for` и `if` всегда пиши с телом в `{ }`, даже если внутри одна инструкция:
            |  `for (i in 0 until 12) { line(...) }` — правильно; `for (i in 0 until 12) line(...)` — ошибка.
            |- Не оставляй пустые `for` — в теле должен быть хотя бы один вызов рисования
            |  (line/circle/gear/moveTo/lineTo/arc/text/fill). Не объявляй `val`, которые не используешь.
            |
            |## Синтаксис
            |
            |Инструкции:
            |
            |- `val имя = выражение` — объявление переменной; `var` работает так же.
            |- `имя = выражение` — присваивание переменной.
            |- `if (условие) { ... } else { ... }` — ветвление.
            |- `for (i in a..b) { ... }` — цикл, включает `b`.
            |- `for (i in a until b) { ... }` — цикл, не включает `b`.
            |- `{ ... }` — блок инструкций.
            |- `// ...` — комментарий до конца строки.
            |- `;` в конце инструкции необязательна.
            |
            |Выражения:
            |
            |- числа: `42`, `3.14` (нельзя `.5` и `1.`);
            |- строки: `"текст"` в двойных кавычках;
            |- арифметика: `+ - * /` (оператора `%` нет);
            |- сравнения: `== != < <= > >=`;
            |- логика с коротким замыканием: `&& || !`;
            |- группировка: `( ... )`, аргументы через `,`;
            |- переменные, вызовы `имя(арг, арг)`, доступ к члену `Math.PI`.
            |
            |## API рисования
            |
            |Координаты — мировые, в миллиметрах; точка `(0, 0)` не обязана быть центром чертежа.
            |
            |- `line(x1, y1, x2, y2)` — отрезок из `(x1, y1)` в `(x2, y2)`.
            |- `rect(x1, y1, x2, y2)` — прямоугольник по двум противоположным углам.
            |- `circle(cx, cy, r)` — окружность с центром `(cx, cy)` и радиусом `r`.
            |- `arc(cx, cy, r, startDeg, endDeg)` — дуга от `startDeg` до `endDeg` (в градусах).
            |- `gear(cx, cy, outerR, innerR, teeth)` — шестерёнка с зубчатым контуром — **единственный правильный
            |  способ её нарисовать**; не собирай шестерёнку вручную из circle/line/arc — контур не замкнётся, зубья не будут видны.
            |- `style(hexColor, thickness, lineType)` — задаёт стиль всей последующей геометрии.
            |  - `hexColor` — `"#RRGGBB"` или `"#AARRGGBB"`;
            |  - `thickness` — толщина линии, например `2.0`;
            |  - `lineType` — `"solid"`, `"dashed"` или `"dotted"`.
            |- `text(x, y, "строка")` — надпись в точке `(x, y)`.
            |- `fill(x, y, hexColor)` — заливка замкнутой грани, содержащей точку `(x, y)`.
            |- `moveTo(x, y)` — поставить «карандаш» в точку (x, y) для построения контура. Не рисует.
            |- `lineTo(x, y)` — провести отрезок из текущего положения карандаша в (x, y); сдвинуть карандаш.
            |- `closePath()` — замкнуть текущий контур (отрезок из текущей точки в стартовую).
            |
            |## Ориентация
            |
            |- Ось X — вправо, ось Y — вверх, единицы — миллиметры.
            |- Если пользователь не указал ориентацию: шляпка болта — сверху (в сторону +Y), резьба — снизу (в сторону −Y).
            |- Для шестерёнки/фланца/симметричных деталей — центр в (0, 0).
            |
            |## Математика
            |
            |- Константы: `PI`, `E` (также работает `Math.PI`).
            |- `sin(x)`, `cos(x)`, `tan(x)` — аргумент в радианах.
            |- `toRadians(deg)`, `toDegrees(rad)` — перевод углов.
            |- `sqrt(x)`, `abs(x)`, `min(a, b)`, `max(a, b)`, `pow(a, b)`.
            |- Допускается префикс `Math.`: `Math.sin(x)`, `Math.toRadians(deg)`.
            |
            |## Ограничения
            |
            |- Используй только функции из списка выше — вызов неизвестной функции прервёт скрипт.
            |- Нет массивов, объектов, лямбд, `while`, `when`, `fun`, `class`, `import`.
            |- `for` — только по диапазону с целыми границами (`a..b` или `a until b`).
            |- Суммарно не более 1 000 000 итераций — иначе скрипт прервётся.
            |
            |## Заливка фигур
            |
            |Чтобы залить фигуру: сначала нарисуй замкнутый контур, затем вызови
            |`fill(x, y, hexColor)` точкой, лежащей внутри контура. Заливки применяются
            |в самом конце прогона, поэтому порядок «контур → fill» надёжен независимо
            |от того, где именно в скрипте стоит `fill`.
            |
            |Для сложных контуров строй их «карандашом»: `moveTo(...)`, затем в цикле `lineTo(...)`,
            |в конце `closePath()`. Замкнутый контур — обязательное условие для `fill(...)`.
            |
            |## Как строить сложные фигуры
            |
            |- Сложную деталь строй **единым замкнутым контуром** через `moveTo(x, y)` → серию `lineTo(x, y)` → `closePath()`. Так делают в CAD: контур один — `fill` его найдёт, швов не будет.
            |- **Не накладывай** фигуры друг на друга, чтобы «склеить» форму: `circle(...)` + 12×`rect(...)` — это 13 разных граней, а не шестерёнка. `fill` заливает **одну** грань.
            |- Исключение — симметричные детали с отверстием: внешний контур (`gear`/`circle`) + отдельная `circle(...)` для отверстия. `fill(...)` вызывай точкой в **теле** детали (между отверстием и впадиной), не внутри отверстия.
            |
            |## Специальные случаи
            |
            |- **Болт.** Рисуй в **одном** виде:
            |  - вид сверху: `circle` шляпки + `circle` стержня + `circle` отверстия (если есть);
            |  - вид сбоку: **прямоугольник** шляпки (не шестигранник!) + прямоугольник стержня + резьба диагональными линиями. Не смешивай виды в одном чертеже.
            |- **Резьба (вид сбоку).** 5–8 диагональных линий с шагом 2–3 мм. Не более 10 линий на 30 мм. Линии резьбы не должны выходить за контур стержня.
            |- **Звезда / шестерня без `gear`.** Чередуй радиусы в цикле: `outerR` на лучах, `innerR` во впадинах. Оператора `%` нет — переключай радиус счётчиком (`var parity = 0`, в цикле `parity = 1 - parity`, затем `if (parity == 0) { r = outerR } else { r = innerR }`), а координаты считай через `cos`/`sin` от угла.
            |- **Рёбра жёсткости (фланец).** Рёбра — часть **внешнего контура** фланца: включай их в единый `moveTo`/`lineTo`/`closePath`, а не рисуй отдельными треугольниками поверх. Иначе `fill` зальёт не то, а отверстия наложатся на рёбра.
            |- **Спирали/пружины** — в LiteScript их нет. Если пользователь просит пружину, нарисуй её как цепочку `arc` (виток = половина `arc`), или верни комментарий `// пружина не поддерживается в LiteScript`.
            |- **Скругления углов** — в LiteScript их нет. Аппроксимируй дугой через `arc(...)` (центр и радиус считай по геометрии), или строй только прямые углы.
            |
            |## Частые ошибки
            |
            |- Не пиши `.5` или `1.` — только `0.5` и `1.0`.
            |- Нет оператора `%` — остаток вычисляй явно через `/` и `*`.
            |- Не забывай закрывающую `}` у `if` и `for`.
            |- Границы `for` должны быть целыми числами.
            |- `fill` осмысленен только для замкнутого контура.
            |- Не собирай шестерёнку вручную — используй `gear(...)`.
            |- Не оставляй `for` без `{ }` и без вызовов рисования внутри.
            |- Не собирай сложную форму из наложенных `circle`/`rect` — строй единый контур через `moveTo`/`lineTo`/`closePath`.
            |- Для шестерёнки с отверстием: `gear(...)` + `circle(...)` отверстие, `fill(...)` — точкой в теле (не в отверстии).
            |- Не смешивай вид сверху и сбоку в одном чертеже болта — выбери один.
            |- Резьба: 5–8 линий, не 20+; не выходи за контур стержня.
            |- Рёбра фланца — часть внешнего контура, а не отдельные треугольники поверх.
            |- Спиралей и скруглений углов в LiteScript нет — не пытайся их изобразить.
            |
            |## Примеры
            |
            |Шестерёнка с подписью:
            |
            |```
            |$SAMPLE_GEAR_SCRIPT
            |```
            |
            |Шестерёнка с отверстием и заливкой:
            |
            |```
            |$SAMPLE_GEAR_FILLED_SCRIPT
            |```
            |
            |Фланец с отверстиями по окружности:
            |
            |```
            |$SAMPLE_FLANGE_SCRIPT
            |```
            |
            |Прямоугольник с заливкой:
            |
            |```
            |$SAMPLE_FILL_SCRIPT
            |```
            |
            |Болт (шляпка сверху, резьба снизу):
            |
            |```
            |$SAMPLE_BOLT_SCRIPT
            |```
            |
            |Многоугольник через moveTo/lineTo:
            |
            |```
            |$SAMPLE_POLYLINE_SCRIPT
            |```
            |
            |Болт, вид сбоку (правильная ориентация и резьба):
            |
            |```
            |$SAMPLE_BOLT_SIDE_SCRIPT
            |```
            |
            |Звезда 8 лучей (чередование внешнего и внутреннего радиусов):
            |
            |```
            |$SAMPLE_STAR_SCRIPT
            |```
            |
            |## Запрос пользователя:
            |
            |$request
            |
            |## Инструкция
            |
            |Верни только код LiteScript. Без markdown-обёрток и без пояснений.
            |Комментарии `//` внутри кода допустимы.
        """.trimMargin().trim()
    }

    /**
     * Генерирует Markdown-промпт и сохраняет его в системную папку «Загрузки».
     *
     * @param context контекст приложения.
     * @param userPrompt описание того, что нужно нарисовать.
     * @param fileName имя файла; по умолчанию — уникальное с временной меткой.
     * @return имя сохранённого файла или `null` при ошибке.
     */
    fun saveMarkdownToDownloads(
        context: Context,
        userPrompt: String,
        fileName: String = "LiteCAD_AI_Prompt_${System.currentTimeMillis()}$MARKDOWN_EXTENSION"
    ): String? {
        val markdown = generateMarkdown(userPrompt)
        val bytes = markdown.toByteArray(Charsets.UTF_8)
        return if (writeToDownloads(context, bytes, fileName)) fileName else null
    }

    /**
     * Сохранить байты в Downloads через MediaStore (как в DxfExporter).
     * @return true, если успешно.
     */
    private fun writeToDownloads(context: Context, bytes: ByteArray, fileName: String): Boolean {
        val values = ContentValues().apply {
            put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
            put(MediaStore.MediaColumns.MIME_TYPE, MARKDOWN_MIME)
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
            }
        }
        val resolver = context.contentResolver
        val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values) ?: return false
        return try {
            resolver.openOutputStream(uri)?.use { out: OutputStream ->
                out.write(bytes)
            } ?: return false
            true
        } catch (t: Throwable) {
            resolver.delete(uri, null, null)
            false
        }
    }
}
